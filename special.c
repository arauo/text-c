#include <stdio.h>
int main(){
printf("please type\"hello world\"\n");
printf("123\bA\n456\n");
printf("123\b456\n");
printf("123\b\n456\n");
    return 0;
}
/*殊字符：printf中已有双引号，想输出双引号需要在符号前加\。这种用来表达特殊字符或无法表达的控制字符就叫逃逸字符。包括
\n 回车   \r 换行   \b 回退   \"双引号   \'单引号   \\斜杠本身
实际上，控制字符的效果在不同计算机上不完全相同。因为我们的程序是要交给终端处理的，而终端是别人写的一个处理程序的程序，被称为shell，不同shell对控制字符的翻译处理不相同
因此\b一般是回退一格，如
printf("123\bA\n456");
结果就是：
12A
456
\b后面的字符会全部跟在后面，除非换行。而如果不跟东西，一般不会执行，也不会把最后一位删掉。\n一般同时执行回车和换行
*/